"""Pydantic models for API request and response schemas."""

from __future__ import annotations

from pydantic import BaseModel, ConfigDict, Field, field_validator


class TokenUsage(BaseModel):
    """Token consumption statistics for a chat completion."""

    prompt_tokens: int = Field(
        ..., ge=0, description="Tokens consumed by prompt/context"
    )
    completion_tokens: int = Field(..., ge=0, description="Tokens generated by model")
    total_tokens: int = Field(..., ge=0, description="Total tokens used in request")

    model_config = ConfigDict(frozen=True)


class ChatRequest(BaseModel):
    """Inbound chat payload from client."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="User query or greeting sent to assistant",
    )
    conversation_id: str | None = Field(
        default=None,
        description="Optional tracking ID for the conversation session",
    )

    model_config = ConfigDict(str_strip_whitespace=True)

    @field_validator("message")
    @classmethod
    def validate_non_empty(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Message cannot be empty or whitespace only")
        return trimmed


class ChatResponse(BaseModel):
    """Outbound chat response payload returned to client."""

    reply: str = Field(..., description="Assistant response text")
    conversation_id: str = Field(..., description="Conversation identifier")
    model: str = Field(..., description="LLM model identifier used for response")
    usage: TokenUsage = Field(..., description="Token usage statistics")

    model_config = ConfigDict(frozen=True)
